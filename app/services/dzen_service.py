def _session_maker():
    engine = _get_engine()
    return async_sessionmaker(engine, class_=AsyncSession, expire_on_commit=False)


async def get_setting(db: AsyncSession, key: str) -> str | None:
    result = await db.execute(text("SELECT value FROM app_settings WHERE key = :k"), {"k": key})
    row = result.first()
    return row[0] if row else None


async def set_setting(db: AsyncSession, key: str, value: str):
    await db.execute(text("""
        INSERT INTO app_settings (key, value, updated_at) VALUES (:k, :v, NOW())
        ON CONFLICT (key) DO UPDATE SET value = :v, updated_at = NOW()
    """), {"k": key, "v": value})
    await db.commit()


async def ensure_seeded(db: AsyncSession):
    result = await db.execute(text("SELECT COUNT(*) FROM dzen_content_plan"))
    count = result.scalar()
    if count and count > 0:
        return
    for idx, (stage, stage_title, angle) in enumerate(CONTENT_PLAN, start=1):
        await db.execute(text("""
            INSERT INTO dzen_content_plan (sequence, stage, stage_title, angle, status)
            VALUES (:seq, :stage, :stage_title, :angle, 'pending')
        """), {"seq": idx, "stage": stage, "stage_title": stage_title, "angle": angle})
    await db.commit()
    logger.info(f"[Dzen] План серии засеян: {len(CONTENT_PLAN)} статей")


async def get_progress(db: AsyncSession) -> dict:
    result = await db.execute(text("""
        SELECT status, COUNT(*) FROM dzen_content_plan GROUP BY status
    """))
    by_status = {row[0]: row[1] for row in result.fetchall()}
    total = sum(by_status.values())
    return {"total": total, "by_status": by_status}


async def get_next_pending(db: AsyncSession, n: int) -> list[dict]:
    result = await db.execute(text("""
        SELECT id, sequence, stage, stage_title, angle 
        FROM dzen_content_plan 
        WHERE status = 'pending' 
        ORDER BY sequence ASC 
        LIMIT :n
    """), {"n": n})
    return [dict(row._mapping) for row in result.fetchall()]


async def mark_generated(db: AsyncSession, plan_id: int, article_title: str):
    await db.execute(text("""
        UPDATE dzen_content_plan 
        SET status = 'generated', article_title = :title, generated_at = NOW() 
        WHERE id = :id
    """), {"title": article_title, "id": plan_id})
    await db.commit()


