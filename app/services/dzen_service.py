async def generate_article_for_item(item: dict, llm: LLMService) -> dict:
    """Генерирует статью по одному пункту плана. Возвращает attachments + заголовок."""
    user_prompt = (
        f"Этап {item['stage']} серии, рубрика: «{item['stage_title']}». "
        f"Угол подачи этой конкретной статьи (используй как основу заголовка "
        f"и сюжет статьи, но можешь сформулировать заголовок ещё точнее по "
        f"формуле из инструкции): {item['angle']}."
    )

    result = await llm.generate("openai", [
        {"role": "system", "content": ARTICLE_INSTRUCTION},
        {"role": "user", "content": user_prompt},
    ], temperature=0.7)

    raw = result["content"].strip()
    if raw.startswith("```"):
        raw = raw.strip("`")
        if raw.lower().startswith("json"):
            raw = raw[4:].strip()
    data = json.loads(raw)

    titles = data.get("title_options", [])
    article_text = data.get("article_text", "")
    description = data.get("description", "")
    tags = data.get("tags", [])

    chosen_title = titles[0] if titles else item["angle"]

    txt_content = (
        f"=== BESTCONSULTING — Дзен, статья #{item['sequence']}/{TOTAL_ARTICLES} ===\n"
        f"Этап {item['stage']}: {item['stage_title']}\n\n"
        "ВАРИАНТЫ ЗАГОЛОВКА:\n"
        + "\n".join(f"{i + 1}. {t}" for i, t in enumerate(titles)) + "\n\n"
        f"ОПИСАНИЕ (для превью):\n{description}\n\n"
        f"ТЕГИ:\n{', '.join(tags)}\n\n"
        "======================\n"
        "ТЕКСТ СТАТЬИ:\n"
        "======================\n\n"
        f"{article_text}"
    )

    attachments = [{"bytes": txt_content.encode("utf-8"), "filename": f"статья_{item['sequence']:03d}.txt"}]

    return {"title": chosen_title, "attachments": attachments}


async def run_daily_batch():
    """Вызывается планировщиком дважды в день — генерирует ARTICLES_PER_DAY статей и шлёт основателю."""
    Session = _session_maker()
    async with Session() as db:
        try:
            enabled = await get_setting(db, "dzen_enabled")
            if enabled != "true":
                return

            await ensure_seeded(db)
            items = await get_next_pending(db, ARTICLES_PER_DAY)
            if not items:
                await send_message(
                    int(FOUNDER_TELEGRAM_ID),
                    f"📭 Серия статей для Дзен полностью сгенерирована ({TOTAL_ARTICLES}/{TOTAL_ARTICLES})."
                )
                await set_setting(db, "dzen_enabled", "false")
                return

            llm = LLMService()

            for item in items:
                try:
                    result = await generate_article_for_item(item, llm)
                    await send_message(
                        int(FOUNDER_TELEGRAM_ID),
                        f"📝 Статья #{item['sequence']}/{TOTAL_ARTICLES} (этап {item['stage']}: {item['stage_title']})\n«{result['title']}»"
                    )
                    for att in result["attachments"]:
                        await send_document(int(FOUNDER_TELEGRAM_ID), att["bytes"], att["filename"])
                    await mark_generated(db, item["id"], result["title"])
                except Exception as e:
                    logger.error(f"[Dzen] Ошибка генерации статьи #{item['sequence']}: {e}")
                    await send_message(int(FOUNDER_TELEGRAM_ID), f"❌ Ошибка генерации статьи #{item['sequence']}: {str(e)[:200]}")
        except Exception as e:
            logger.error(f"[Dzen] Критическая ошибка daily batch: {e}")


def _ensure_scheduler_started():
    global _scheduler
    if _scheduler is not None:
        return
    from apscheduler.schedulers.asyncio import AsyncIOScheduler
    from apscheduler.triggers.cron import CronTrigger

    _scheduler = AsyncIOScheduler()
    _scheduler.add_job(run_daily_batch, CronTrigger(hour=10, minute=0), id="dzen_morning")
    _scheduler.add_job(run_daily_batch, CronTrigger(hour=16, minute=0), id="dzen_evening")
    _scheduler.start()
    logger.info("[Dzen] Планировщик запущен: 10:00 и 16:00 (время сервера)")


async def start_series(db: AsyncSession) -> str:
    await ensure_seeded(db)
    await set_setting(db, "dzen_enabled", "true")
    _ensure_scheduler_started()
    progress = await get_progress(db)
    return (
        f"✅ Серия запущена. Всего статей: {progress['total']}. "
        f"По {ARTICLES_PER_DAY} статьи в день (10:00 и 16:00), придут сюда в чат."
    )


async def stop_series(db: AsyncSession) -> str:
    await set_setting(db, "dzen_enabled", "false")
    return "⏸ Серия приостановлена. Возобновить — командой /дзен_старт."


